#!/usr/bin/env node
// Generates src/i18n/namespaces.generated.ts (en resources + zh-CN lazy loaders)
// and src/i18n/resources.generated.d.ts (typed keys for t()).
// Source of truth: src/i18n/locales/en/*.json. Run: npm run i18n:types
import fs from "node:fs";
import path from "node:path";

const DIR = path.join(process.cwd(), "src/i18n");
const LANGS = ["zh-CN"];
const nss = fs.readdirSync(path.join(DIR, "locales/en")).filter((f) => f.endsWith(".json")).map((f) => f.slice(0, -5)).sort();
const id = (ns) => "en_" + ns.replace(/[^A-Za-z0-9]/g, "_");
const head = "// Generated by scripts/i18n/gen-types.mjs. Do not edit by hand.\n";

let ts = head;
for (const ns of nss) ts += `import ${id(ns)} from "./locales/en/${ns}.json";\n`;
ts += `\nexport const namespaces = ${JSON.stringify(nss, null, 2)} as const;\n`;
ts += `export type Namespace = (typeof namespaces)[number];\n\n`;
ts += `export const enResources = {\n${nss.map((ns) => `  ${JSON.stringify(ns)}: ${id(ns)},`).join("\n")}\n};\n\n`;
ts += `export const loaders: Record<string, Record<Namespace, () => Promise<{ default: Record<string, string> }>>> = {\n`;
for (const l of LANGS) ts += `  ${JSON.stringify(l)}: {\n${nss.map((ns) => `    ${JSON.stringify(ns)}: () => import("./locales/${l}/${ns}.json"),`).join("\n")}\n  },\n`;
ts += "};\n";
fs.writeFileSync(path.join(DIR, "namespaces.generated.ts"), ts);

let dts = head + `import "i18next";\n\ndeclare module "i18next" {\n  interface CustomTypeOptions {\n    defaultNS: "common";\n    keySeparator: false;\n    nsSeparator: ":";\n    resources: {\n`;
for (const ns of nss) dts += `      ${JSON.stringify(ns)}: typeof import("./locales/en/${ns}.json");\n`;
dts += `    };\n  }\n}\n`;
fs.writeFileSync(path.join(DIR, "resources.generated.d.ts"), dts);
console.log(`i18n:types: ${nss.length} namespaces`);
